def fibonacci(count):
    if count <= 0:
        raise ValueError("Enter a positive number of terms.")

    sequence = [0, 1]

    while len(sequence) < count:
        sequence.append(sequence[-1] + sequence[-2])

    return sequence[:count]

terms = 10
print(f"First {terms} Fibonacci numbers: {fibonacci(terms)}")